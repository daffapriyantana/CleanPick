import '../../core/constants/app_constants.dart';
import '../../domain/entities/order_entity.dart';

class OrderModel extends OrderEntity {
  const OrderModel({
    required super.id,
    required super.wasteType,
    required super.weightKg,
    required super.address,
    required super.pickupDate,
    required super.vehicleType,
    required super.baseFee,
    required super.distanceFee,
    required super.weightFee,
    required super.totalPrice,
    required super.status,
    required super.paymentStatus,
    required super.createdAt,
    super.note,
    super.officerName,
    super.photoPath,
    super.latitude,
    super.longitude,
    super.paymentMethod,
    super.wasteTypes,
    super.customerId,
    super.customerName,
    super.officerRating,
    super.complaint,
  });

  factory OrderModel.fromJson(Map<String, dynamic> json) {
    return OrderModel(
      id: json['id'] as String,
      wasteType: WasteType.values[json['wasteType'] as int],
      weightKg: (json['weightKg'] as num).toDouble(),
      address: json['address'] as String,
      pickupDate: DateTime.parse(json['pickupDate'] as String),
      vehicleType: VehicleType.values[json['vehicleType'] as int],
      baseFee: (json['baseFee'] as num).toDouble(),
      distanceFee: (json['distanceFee'] as num).toDouble(),
      weightFee: (json['weightFee'] as num).toDouble(),
      totalPrice: (json['totalPrice'] as num).toDouble(),
      status: OrderStatus.values[json['status'] as int],
      paymentStatus: PaymentStatus.values[json['paymentStatus'] as int],
      createdAt: DateTime.parse(json['createdAt'] as String),
      note: json['note'] as String?,
      officerName: json['officerName'] as String?,
      photoPath: json['photoPath'] as String?,
      latitude: (json['latitude'] as num?)?.toDouble(),
      longitude: (json['longitude'] as num?)?.toDouble(),
      paymentMethod: PaymentMethod.values[json['paymentMethod'] as int? ?? 0],
      wasteTypes: (json['wasteTypes'] as List<dynamic>?)
              ?.map((value) => WasteType.values[value as int])
              .toList() ??
          const [],
      customerId: json['customerId'] as String?,
      customerName: json['customerName'] as String?,
      officerRating: json['officerRating'] as int?,
      complaint: json['complaint'] as String?,
    );
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'wasteType': wasteType.index,
        'weightKg': weightKg,
        'address': address,
        'pickupDate': pickupDate.toIso8601String(),
        'vehicleType': vehicleType.index,
        'baseFee': baseFee,
        'distanceFee': distanceFee,
        'weightFee': weightFee,
        'totalPrice': totalPrice,
        'status': status.index,
        'paymentStatus': paymentStatus.index,
        'createdAt': createdAt.toIso8601String(),
        'note': note,
        'officerName': officerName,
        'photoPath': photoPath,
        'latitude': latitude,
        'longitude': longitude,
        'paymentMethod': paymentMethod.index,
        'wasteTypes': wasteTypes.map((type) => type.index).toList(),
        'customerId': customerId,
        'customerName': customerName,
        'officerRating': officerRating,
        'complaint': complaint,
      };

  factory OrderModel.fromEntity(OrderEntity e) => OrderModel(
        id: e.id,
        wasteType: e.wasteType,
        weightKg: e.weightKg,
        address: e.address,
        pickupDate: e.pickupDate,
        vehicleType: e.vehicleType,
        baseFee: e.baseFee,
        distanceFee: e.distanceFee,
        weightFee: e.weightFee,
        totalPrice: e.totalPrice,
        status: e.status,
        paymentStatus: e.paymentStatus,
        createdAt: e.createdAt,
        note: e.note,
        officerName: e.officerName,
        photoPath: e.photoPath,
        latitude: e.latitude,
        longitude: e.longitude,
        paymentMethod: e.paymentMethod,
        wasteTypes: e.wasteTypes,
        customerId: e.customerId,
        customerName: e.customerName,
        officerRating: e.officerRating,
        complaint: e.complaint,
      );
}
